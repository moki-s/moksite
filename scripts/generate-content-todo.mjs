// Generates docs/CONTENT-TODO.md — a checklist of every unresolved
// [TODO-CONTENT] marker. Runs on every build (package.json `prebuild`).
// Phase 7 blocks launch until this file shows zero open items (PRD §0.2).
//
// Scans the *content surfaces* only — MDX cases, typed site content, and app
// pages — so the marker-handling code in src/lib and this script aren't
// falsely flagged, and the marker's literal appearances in docs/ are ignored.
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const MARKER = "[TODO-CONTENT]";
const SCAN_DIRS = ["content", "src/content", "src/app"];
const EXTS = new Set([".mdx", ".md", ".ts", ".tsx"]);
const SKIP_DIRS = new Set(["node_modules", ".next", ".git"]);

function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(path.join(dir, entry.name), acc);
    } else if (EXTS.has(path.extname(entry.name))) {
      acc.push(path.join(dir, entry.name));
    }
  }
  return acc;
}

const files = SCAN_DIRS.flatMap((dir) => walk(path.join(ROOT, dir)));

const byFile = new Map();
let total = 0;
for (const file of files) {
  const rel = path.relative(ROOT, file).split(path.sep).join("/");
  const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
  lines.forEach((line, index) => {
    if (line.includes(MARKER)) {
      if (!byFile.has(rel)) byFile.set(rel, []);
      byFile.get(rel).push({ line: index + 1, text: line.trim() });
      total += 1;
    }
  });
}

let out = "# Content TODO\n\n";
out += "_Auto-generated by `scripts/generate-content-todo.mjs` on every build._\n\n";
out += `Lists every unresolved \`${MARKER}\` marker. **Phase 7 blocks launch until this file shows zero open items.**\n\n`;
out += `**Open items: ${total}** across ${byFile.size} file(s).\n\n`;

if (total === 0) {
  out += "_No unresolved markers — clear on this axis._\n";
} else {
  for (const [rel, items] of [...byFile.entries()].sort()) {
    out += `## \`${rel}\`\n\n`;
    for (const item of items) {
      const snippet = item.text.length > 100 ? `${item.text.slice(0, 100)}…` : item.text;
      out += `- [ ] L${item.line}: \`${snippet.replaceAll("`", "ˋ")}\`\n`;
    }
    out += "\n";
  }
}

fs.writeFileSync(path.join(ROOT, "docs", "CONTENT-TODO.md"), out, "utf8");
console.log(`[content-todo] ${total} marker(s) across ${byFile.size} file(s) -> docs/CONTENT-TODO.md`);
